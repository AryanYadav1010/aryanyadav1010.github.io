// Get alpha-2 code from various inputs (numeric ID, alpha-3, or name)
export function getAlpha2Code(input) {
  if (!input) return null;
  
  const strInput = String(input);
  
  // Check if it's a numeric ID (UN M49)
  const paddedNumeric = strInput.padStart(3, '0');
  if (numericToAlpha2[paddedNumeric]) {
    return numericToAlpha2[paddedNumeric];
  }
  
  // Try the raw numeric value
  if (numericToAlpha2[strInput]) {
    return numericToAlpha2[strInput];
  }
  
  // Check if it's already an alpha-2 code
  if (strInput.length === 2) {
    return strInput.toLowerCase();
  }
  
  // Check if it's an alpha-3 code
  const upperInput = strInput.toUpperCase();
  if (alpha3ToAlpha2[upperInput]) {
    return alpha3ToAlpha2[upperInput];
  }
  
  return null;
}

// Get country name from TopoJSON geography properties
export function getCountryName(geo) {
  if (!geo || !geo.properties) return "Unknown";
  return geo.properties.name || geo.properties.NAME || geo.properties.ADMIN || "Unknown";
}
